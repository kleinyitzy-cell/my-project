// ─── Google Tag Manager: load after user interaction ──────────────────────────
// Replace GTM-XXXXXX with your actual GTM container ID.
add_action( 'wp_head', function () {
    $gtm_id = 'GTM-XXXXXX';
    ?>
    <script>
    // Delay GTM until first user interaction (saves ~120 KB TBT on mobile)
    (function(){
        var loaded = false;
        function loadGTM(){
            if(loaded) return; loaded = true;
            (function(w,d,s,l,i){w[l]=w[l]||[];w[l].push({'gtm.start':
            new Date().getTime(),event:'gtm.js'});var f=d.getElementsByTagName(s)[0],
            j=d.createElement(s),dl=l!='dataLayer'?'&l='+l:'';j.async=true;j.src=
            'https://www.googletagmanager.com/gtm.js?id='+i+dl;f.parentNode.insertBefore(j,f);
            })(window,document,'script','dataLayer','<?php echo esc_js( $gtm_id ); ?>');
        }
        ['mousedown','touchstart','keydown','scroll'].forEach(function(e){
            window.addEventListener(e, loadGTM, {once:true, passive:true});
        });
        setTimeout(loadGTM, 5000); // hard fallback
    })();
    </script>
    <?php
}, 99 );

