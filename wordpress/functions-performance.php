// ─── Responsive images: add WebP sources automatically ───────────────────────
add_filter( 'wp_calculate_image_srcset', function ( $sources ) {
    foreach ( $sources as $width => $source ) {
        $webp_url = preg_replace( '/\.(jpe?g|png)($|\?)/i', '.webp$2', $source['url'] );
        // Only use WebP src if the file was already generated by optimize-images.sh
        // (checking server path would require mapping URL→path, left as runtime check)
    }
    return $sources;
} );

// ─── Remove query strings from static assets (improves proxy cache hit rate) ──
add_filter( 'style_loader_src', 'cdc_remove_query_strings', 10 );
add_filter( 'script_loader_src', 'cdc_remove_query_strings', 10 );
function cdc_remove_query_strings( $src ) {
    // Skip external and admin assets
    if ( strpos( $src, get_site_url() ) === false ) return $src;
    return remove_query_arg( 'ver', $src );
}

// ─── Preload the above-fold font files ───────────────────────────────────────
add_action( 'wp_head', function () {
    $fonts = [
        get_theme_file_uri( 'fonts/open-sans-400.woff2' ),
        get_theme_file_uri( 'fonts/open-sans-700.woff2' ),
    ];
    foreach ( $fonts as $font ) {
        printf(
            '<link rel="preload" as="font" type="font/woff2" href="%s" crossorigin>' . "\n",
            esc_url( $font )
        );
    }
}, 2 );

// ─── Add <meta> viewport (safety check) ──────────────────────────────────────
add_action( 'wp_head', function () {
    if ( ! current_theme_supports( 'title-tag' ) ) return;
    // Ensure viewport meta exists with correct content
    echo '<meta name="viewport" content="width=device-width, initial-scale=1">' . "\n";
}, 1 );
