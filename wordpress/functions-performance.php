// ─── Register performance JS with defer ───────────────────────────────────────
add_action( 'wp_enqueue_scripts', function () {
    wp_enqueue_script(
        'cdc-performance',
        get_theme_file_uri( 'js/performance.js' ),
        [],
        '1.0.0',
        [ 'strategy' => 'defer', 'in_footer' => true ]
    );
} );

// ─── Add fetchpriority="high" to hero/LCP image ───────────────────────────────
add_filter( 'wp_get_attachment_image_attributes', function ( $attr, $attachment, $size ) {
    // Tag the first image inserted with [hero] shortcode or specific attachment ID
    static $hero_loaded = false;
    if ( ! $hero_loaded && ( isset( $attr['class'] ) && strpos( $attr['class'], 'hero' ) !== false ) ) {
        $attr['fetchpriority'] = 'high';
        $attr['loading']       = 'eager';
        $hero_loaded = true;
    }
    return $attr;
}, 10, 3 );

